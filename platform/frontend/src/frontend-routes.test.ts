import { afterEach, describe, expect, it } from 'vitest'
import { spawnSync } from 'child_process'
import fs from 'fs'
import os from 'os'
import path from 'path'

// scripts/frontend-routes.mjs generates the host app's page/layout/route stubs
// from each SIET part's own frontend/src/app. These tests run the script (as a
// child process, like `make frontend-routes` does) against a throw-away copy of
// the layout, and `--check` against the real tree.

const REPO_ROOT = path.resolve(__dirname, '../../..')
const SCRIPT = path.join(REPO_ROOT, 'scripts', 'frontend-routes.mjs')
const MARKER = '// generated by scripts/frontend-routes.mjs - edit the page in its part'
const HOST_APP = 'platform/frontend/src/app'

const tempRoots: string[] = []

function makeTree(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'frontend-routes-'))
  tempRoots.push(root)
  fs.mkdirSync(path.join(root, 'scripts'), { recursive: true })
  fs.copyFileSync(SCRIPT, path.join(root, 'scripts', 'frontend-routes.mjs'))
  fs.mkdirSync(path.join(root, HOST_APP), { recursive: true })
  return root
}

function write(root: string, rel: string, content: string) {
  const file = path.join(root, rel)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, content)
}

function read(root: string, rel: string): string {
  return fs.readFileSync(path.join(root, rel), 'utf8')
}

function exists(root: string, rel: string): boolean {
  return fs.existsSync(path.join(root, rel))
}

function run(root: string, ...args: string[]) {
  const result = spawnSync(process.execPath, [path.join(root, 'scripts', 'frontend-routes.mjs'), ...args], {
    cwd: os.tmpdir(), // the script resolves paths from its own location, not the cwd
    encoding: 'utf8',
  })
  return { status: result.status, stdout: result.stdout, stderr: result.stderr }
}

const PAGE_SRC = 'export default function Page() {\n  return null\n}\n'

afterEach(() => {
  while (tempRoots.length) {
    fs.rmSync(tempRoots.pop() as string, { recursive: true, force: true })
  }
})

describe('frontend-routes', () => {
  it('generates_stub_for_new_page', () => {
    const root = makeTree()
    write(root, 'community/frontend/src/app/(dashboard)/community/x/page.tsx', PAGE_SRC)

    const result = run(root)

    expect(result.status, result.stderr).toBe(0)
    expect(read(root, `${HOST_APP}/(dashboard)/community/x/page.tsx`)).toBe(
      `${MARKER}\nexport { default } from '@siet/community/app/(dashboard)/community/x/page'\n`
    )
  })

  it('removes_orphan_stub', () => {
    const root = makeTree()
    const source = 'community/frontend/src/app/(dashboard)/community/x/page.tsx'
    const stub = `${HOST_APP}/(dashboard)/community/x/page.tsx`
    write(root, source, PAGE_SRC)
    write(root, `${HOST_APP}/(dashboard)/dashboard/page.tsx`, PAGE_SRC) // real host page, no marker
    expect(run(root).status).toBe(0)
    expect(exists(root, stub)).toBe(true)

    fs.rmSync(path.join(root, source))
    const result = run(root)

    expect(result.status, result.stderr).toBe(0)
    expect(exists(root, stub)).toBe(false)
    // the directory the stub lived in is pruned too, hand-written pages stay
    expect(exists(root, `${HOST_APP}/(dashboard)/community`)).toBe(false)
    expect(read(root, `${HOST_APP}/(dashboard)/dashboard/page.tsx`)).toBe(PAGE_SRC)
  })

  it('refuses_hand_written_file', () => {
    const root = makeTree()
    const host = `${HOST_APP}/(dashboard)/community/x/page.tsx`
    const real = "export default function RealHostPage() {\n  return <p>hand written</p>\n}\n"
    write(root, 'community/frontend/src/app/(dashboard)/community/x/page.tsx', PAGE_SRC)
    write(root, 'community/frontend/src/app/(dashboard)/community/y/page.tsx', PAGE_SRC)
    write(root, host, real)

    const result = run(root)

    expect(result.status).toBe(2)
    expect(result.stderr).toContain('(dashboard)/community/x/page.tsx')
    expect(read(root, host)).toBe(real)
    // nothing else is written when one path is refused
    expect(exists(root, `${HOST_APP}/(dashboard)/community/y/page.tsx`)).toBe(false)
  })

  it('check_passes_on_the_real_tree', () => {
    const result = spawnSync(process.execPath, [SCRIPT, '--check'], { cwd: os.tmpdir(), encoding: 'utf8' })

    expect(result.status, `${result.stdout}${result.stderr}`).toBe(0)
  })

  it('check_lists_pending_changes_and_writes_nothing', () => {
    const root = makeTree()
    write(root, 'my-ai-quiz/frontend/src/app/(dashboard)/admin/quiz/page.tsx', PAGE_SRC)

    const result = run(root, '--check')

    expect(result.status).toBe(1)
    expect(result.stdout).toContain(`${HOST_APP}/(dashboard)/admin/quiz/page.tsx`)
    expect(exists(root, `${HOST_APP}/(dashboard)/admin/quiz/page.tsx`)).toBe(false)
  })

  it('check_reports_an_orphan_without_deleting_it', () => {
    const root = makeTree()
    const orphan = `${HOST_APP}/(dashboard)/gone/page.tsx`
    write(root, orphan, `${MARKER}\nexport { default } from '@siet/community/app/(dashboard)/gone/page'\n`)

    const result = run(root, '--check')

    expect(result.status).toBe(1)
    expect(result.stdout).toContain(orphan)
    expect(exists(root, orphan)).toBe(true)
  })

  it('uses_the_alias_of_each_part', () => {
    const root = makeTree()
    write(root, 'kmitl-rag/frontend/src/app/(dashboard)/a/page.tsx', PAGE_SRC)
    write(root, 'my-ai-quiz/frontend/src/app/(dashboard)/b/page.tsx', PAGE_SRC)
    write(root, 'ai-roadmap/frontend/src/app/(dashboard)/c/page.tsx', PAGE_SRC)

    expect(run(root).status).toBe(0)

    expect(read(root, `${HOST_APP}/(dashboard)/a/page.tsx`)).toContain("from '@siet/kmitl-rag/app/(dashboard)/a/page'")
    expect(read(root, `${HOST_APP}/(dashboard)/b/page.tsx`)).toContain("from '@siet/quiz/app/(dashboard)/b/page'")
    expect(read(root, `${HOST_APP}/(dashboard)/c/page.tsx`)).toContain("from '@siet/roadmap/app/(dashboard)/c/page'")
  })

  it('only_generates_for_page_layout_route_loading_error_and_not_found', () => {
    const root = makeTree()
    const dir = 'community/frontend/src/app/(dashboard)/z'
    for (const name of ['page.tsx', 'layout.tsx', 'loading.tsx', 'not-found.tsx', 'route.ts']) {
      write(root, `${dir}/${name}`, PAGE_SRC)
    }
    write(root, `${dir}/error.tsx`, "'use client'\n" + PAGE_SRC)
    write(root, `${dir}/page.test.tsx`, PAGE_SRC)
    write(root, `${dir}/components/Card.tsx`, PAGE_SRC)
    write(root, `${dir}/helpers.ts`, PAGE_SRC)

    expect(run(root).status).toBe(0)

    const generated = fs.readdirSync(path.join(root, HOST_APP, '(dashboard)/z')).sort()
    expect(generated).toEqual(['error.tsx', 'layout.tsx', 'loading.tsx', 'not-found.tsx', 'page.tsx', 'route.ts'])
  })

  it('reexports_metadata_and_viewport_but_copies_the_rest_as_literals', () => {
    const root = makeTree()
    write(
      root,
      'community/frontend/src/app/(dashboard)/m/page.tsx',
      [
        "import type { Metadata } from 'next'",
        "// export const revalidate = 5   (a comment is not an export)",
        "export const dynamic = 'force-dynamic'",
        'export const revalidate = 60',
        'export async function generateMetadata(): Promise<Metadata> { return {} }',
        'const viewport = {}',
        'export { viewport }',
        'export type { Metadata }',
        'export function helper() {}',
        'export default function Page() { return null }',
        '',
      ].join('\n')
    )

    expect(run(root).status).toBe(0)

    // Turbopack refuses `export { dynamic } from '...'` ("mustn't be reexported"), so the
    // statically read names are written out as literals; the rest re-export fine.
    expect(read(root, `${HOST_APP}/(dashboard)/m/page.tsx`)).toBe(
      `${MARKER}\n` +
        "export { default, generateMetadata, viewport } from '@siet/community/app/(dashboard)/m/page'\n" +
        "export const dynamic = 'force-dynamic'\n" +
        'export const revalidate = 60\n'
    )
  })

  it('copies_every_statically_read_name_as_a_literal', () => {
    const root = makeTree()
    write(
      root,
      'community/frontend/src/app/(dashboard)/c/page.tsx',
      [
        'export const maxDuration = 30 // seconds',
        "export const preferredRegion = 'auto'",
        'export const fetchCache: string = "force-no-store";',
        "export const runtime = 'nodejs'",
        'export const dynamicParams = false',
        "export const dynamic = 'error'",
        'export const revalidate = 0.5',
        'export default function Page() { return null }',
        '',
      ].join('\n')
    )

    expect(run(root).status).toBe(0)

    expect(read(root, `${HOST_APP}/(dashboard)/c/page.tsx`)).toBe(
      `${MARKER}\n` +
        "export { default } from '@siet/community/app/(dashboard)/c/page'\n" +
        "export const dynamic = 'error'\n" +
        'export const dynamicParams = false\n' +
        "export const runtime = 'nodejs'\n" +
        'export const revalidate = 0.5\n' +
        'export const fetchCache = "force-no-store"\n' +
        "export const preferredRegion = 'auto'\n" +
        'export const maxDuration = 30\n'
    )
  })

  it('refuses_segment_config_that_is_not_a_literal', () => {
    const root = makeTree()
    const host = `${HOST_APP}/(dashboard)/n/page.tsx`
    write(
      root,
      'community/frontend/src/app/(dashboard)/n/page.tsx',
      "const cond = Math.random() > 0.5\nexport const dynamic = cond ? 'a' : 'b'\n" + PAGE_SRC
    )
    write(root, 'community/frontend/src/app/(dashboard)/ok/page.tsx', PAGE_SRC)

    const result = run(root)

    expect(result.status).toBe(2)
    expect(result.stderr).toContain('(dashboard)/n/page.tsx: dynamic must be a literal so the route stub can copy it')
    expect(exists(root, host)).toBe(false)
    // nothing else is written when one page is refused
    expect(exists(root, `${HOST_APP}/(dashboard)/ok/page.tsx`)).toBe(false)
  })

  it('refuses_segment_config_exported_through_a_list', () => {
    const root = makeTree()
    write(
      root,
      'community/frontend/src/app/(dashboard)/l/page.tsx',
      "const revalidate = 60\nexport { revalidate }\n" + PAGE_SRC
    )

    const result = run(root)

    expect(result.status).toBe(2)
    expect(result.stderr).toContain('(dashboard)/l/page.tsx: revalidate must be a literal so the route stub can copy it')
  })

  it('route_files_are_star_re_exports_with_copied_config', () => {
    const root = makeTree()
    write(
      root,
      'community/frontend/src/app/api/thing/route.ts',
      "export const dynamic = 'force-dynamic'\nexport async function GET() { return new Response('ok') }\n"
    )
    write(
      root,
      'community/frontend/src/app/api/plain/route.ts',
      "export async function GET() { return new Response('ok') }\n"
    )

    expect(run(root).status).toBe(0)

    expect(read(root, `${HOST_APP}/api/thing/route.ts`)).toBe(
      `${MARKER}\nexport * from '@siet/community/app/api/thing/route'\nexport const dynamic = 'force-dynamic'\n`
    )
    expect(read(root, `${HOST_APP}/api/plain/route.ts`)).toBe(
      `${MARKER}\nexport * from '@siet/community/app/api/plain/route'\n`
    )
  })

  it('error_files_stay_client_components', () => {
    const root = makeTree()
    write(root, 'community/frontend/src/app/(dashboard)/e/error.tsx', "'use client'\n" + PAGE_SRC)

    expect(run(root).status).toBe(0)

    expect(read(root, `${HOST_APP}/(dashboard)/e/error.tsx`)).toBe(
      `${MARKER}\n'use client'\nexport { default } from '@siet/community/app/(dashboard)/e/error'\n`
    )
  })

  it('converts_the_old_one_line_stub_but_nothing_else', () => {
    const root = makeTree()
    const specifier = '@siet/community/app/(dashboard)/old/page'
    write(root, 'community/frontend/src/app/(dashboard)/old/page.tsx', PAGE_SRC)
    write(root, `${HOST_APP}/(dashboard)/old/page.tsx`, `export { default } from '${specifier}'\n`)
    // same shape, but it points at another module: that is not the stub the script would write
    write(root, 'community/frontend/src/app/(dashboard)/other/page.tsx', PAGE_SRC)
    write(root, `${HOST_APP}/(dashboard)/other/page.tsx`, "export { default } from '@siet/kmitl-rag/app/(dashboard)/other/page'\n")

    const result = run(root)

    expect(result.status).toBe(2)
    expect(result.stderr).toContain('(dashboard)/other/page.tsx')
    expect(result.stderr).not.toContain('(dashboard)/old/page.tsx')

    fs.rmSync(path.join(root, HOST_APP, '(dashboard)/other'), { recursive: true })
    fs.rmSync(path.join(root, 'community/frontend/src/app/(dashboard)/other'), { recursive: true })
    expect(run(root).status).toBe(0)
    expect(read(root, `${HOST_APP}/(dashboard)/old/page.tsx`)).toBe(`${MARKER}\nexport { default } from '${specifier}'\n`)
  })

  it('refuses_a_page_defined_by_two_parts', () => {
    const root = makeTree()
    write(root, 'community/frontend/src/app/(dashboard)/dup/page.tsx', PAGE_SRC)
    write(root, 'kmitl-rag/frontend/src/app/(dashboard)/dup/page.tsx', PAGE_SRC)

    const result = run(root)

    expect(result.status).toBe(2)
    expect(result.stderr).toContain('(dashboard)/dup/page.tsx')
    expect(exists(root, `${HOST_APP}/(dashboard)/dup/page.tsx`)).toBe(false)
  })
})
